-- 1. Profiles Table (extends Supabase auth.users or standalone)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    auth_user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'prosumer' CHECK (role IN ('prosumer', 'discom_operator', 'society_admin')),
    home_id TEXT DEFAULT 'H00',
    upi_vpa TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Feeder Telemetry Table (Time-Series for Grid Operators)
CREATE TABLE IF NOT EXISTS public.feeder_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    city TEXT NOT NULL,
    feeder_name TEXT NOT NULL,
    net_kw NUMERIC NOT NULL,
    baseline_kw NUMERIC NOT NULL,
    solar_kw NUMERIC NOT NULL,
    battery_soc NUMERIC NOT NULL,
    peak_cut_pct NUMERIC NOT NULL,
    co2_kg NUMERIC NOT NULL
);

-- 3. Demand Response Events Table
CREATE TABLE IF NOT EXISTS public.dr_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_code TEXT UNIQUE NOT NULL,
    trigger_type TEXT NOT NULL,
    target_kw NUMERIC NOT NULL,
    achieved_kw NUMERIC NOT NULL,
    start_time TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    duration_min INTEGER NOT NULL,
    homes_count INTEGER NOT NULL,
    incentive_inr NUMERIC NOT NULL
);

-- 4. Micro-Incentive Wallet Transactions (UPI Rails)
CREATE TABLE IF NOT EXISTS public.wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_id TEXT NOT NULL,
    amount_inr NUMERIC NOT NULL,
    action_type TEXT NOT NULL,
    upi_ref TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Community Flexible Devices Registry
CREATE TABLE IF NOT EXISTS public.device_registry (
    id TEXT PRIMARY KEY,
    home_id TEXT NOT NULL,
    device_kind TEXT NOT NULL,
    power_kw NUMERIC NOT NULL,
    is_flexible BOOLEAN DEFAULT true,
    opt_in BOOLEAN DEFAULT true,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indexes for lightning fast queries
CREATE INDEX IF NOT EXISTS idx_feeder_telemetry_time ON public.feeder_telemetry (recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_dr_events_time ON public.dr_events (start_time DESC);
CREATE INDEX IF NOT EXISTS idx_wallet_home ON public.wallet_transactions (home_id, created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feeder_telemetry ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dr_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wallet_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_registry ENABLE ROW LEVEL SECURITY;

-- Transparent Public / Authenticated Read Policies
CREATE POLICY "Public profiles can be read" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Public telemetry can be read" ON public.feeder_telemetry FOR SELECT USING (true);
CREATE POLICY "Public DR events can be read" ON public.dr_events FOR SELECT USING (true);
CREATE POLICY "Public transactions can be read" ON public.wallet_transactions FOR SELECT USING (true);
CREATE POLICY "Device registry can be read" ON public.device_registry FOR SELECT USING (true);

-- Allow Insert / Update from service role or authenticated users
CREATE POLICY "Service and auth insert profiles" ON public.profiles FOR ALL USING (true);
CREATE POLICY "Service and auth insert telemetry" ON public.feeder_telemetry FOR ALL USING (true);
CREATE POLICY "Service and auth insert dr_events" ON public.dr_events FOR ALL USING (true);
CREATE POLICY "Service and auth insert transactions" ON public.wallet_transactions FOR ALL USING (true);
CREATE POLICY "Service and auth insert devices" ON public.device_registry FOR ALL USING (true);
